/*
  Wraps the vendored three.js ES module build (tools/vendor/three.module.min.js)
  as a classic script that sets window.THREE, written to assets/a3gk-three.js.

  Why: loading ES modules from Shopify's CDN with import() can fail on some
  browsers/CDN setups (module scripts need CORS). A classic <script> always
  loads. Run after replacing the vendored three.js file:
    node tools/build-three-global.mjs
*/
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = fs.readFileSync(path.join(ROOT, 'tools/vendor/three.module.min.js'), 'utf8');
const m = src.match(/export\s*\{([^}]*)\};?\s*$/);
if (!m) throw new Error('Could not find the export list at the end of the three.js module');
if (/(^|[;}])\s*import\s*[{*\s]|\bimport\.meta\b/.test(src.slice(0, m.index))) throw new Error('three.js module has imports; cannot wrap');
const pairs = m[1]
  .split(',')
  .map((s) => s.trim())
  .filter(Boolean)
  .map((s) => {
    const [local, , exported] = s.split(/\s+/);
    return `${JSON.stringify(exported || local)}:${local}`;
  });
const body = src.slice(0, m.index);
const header = src.match(/^\/\*\*[\s\S]*?\*\//)?.[0] || '';
const out = `${header}\n/* Classic-script wrapper generated by tools/build-three-global.mjs. */\n(function(){${body.slice(header.length)}\nwindow.THREE=Object.freeze({${pairs.join(',')}});})();\n`;
fs.writeFileSync(path.join(ROOT, 'assets/a3gk-three.js'), out);
console.log(`assets/a3gk-three.js written (${pairs.length} exports, ${(out.length / 1024).toFixed(0)} KB)`);
