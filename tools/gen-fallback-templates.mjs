/*
  Generates the built-in ("fallback") views that make every A3GK page work on a
  fresh store, before any pages/collections/blog exist in Shopify admin.

  Shopify only serves /pages/x once a page with that handle exists. The
  homepage always exists, and it accepts alternate templates via ?view=, so
  each page also ships as templates/index.<view>.json. snippets/a3gk-href
  sends links to those views until the real page exists, then to the page.

  Writes:
    templates/index.<page>.json         copies of templates/page.<page>.json
    templates/index.c-<collection>.json placeholder collection views
    templates/index.guides.json         guide list
    templates/index.guide-<handle>.json each guide from content/guides
    snippets/a3gk-view-title.liquid     <title> text for each view
  and normalises shopify:// links in templates to plain paths so they can be
  resolved at render time.

  Run after editing page templates or guides:  npm run gen:fallbacks
*/
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { marked } from 'marked';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const T = (f) => path.join(ROOT, 'templates', f);
const readJSON = (f) => JSON.parse(fs.readFileSync(f, 'utf8').replace(/^\s*\/\*[\s\S]*?\*\//, ''));
const writeJSON = (f, d) => fs.writeFileSync(f, JSON.stringify(d, null, 2) + '\n');
const HEADER = '/*\n * Generated by tools/gen-fallback-templates.mjs. Edit the source template or\n * content/guides, then run: npm run gen:fallbacks\n */\n';
const writeGenerated = (f, d) => fs.writeFileSync(f, HEADER + JSON.stringify(d, null, 2) + '\n');

const titles = {};

/* 1. shopify:// → plain paths, so links can be resolved at render time */
const toPath = (v) =>
  typeof v === 'string'
    ? v.replace(/^shopify:\/\/(pages|collections|blogs|products)\//, '/$1/').replace(/^shopify:\/\/policies\//, '/policies/')
    : v;
function normalise(obj) {
  if (Array.isArray(obj)) return obj.map(normalise);
  if (obj && typeof obj === 'object') return Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, normalise(v)]));
  return toPath(obj);
}
const sources = [
  ...fs.readdirSync(path.join(ROOT, 'templates')).filter((f) => f.endsWith('.json') && !f.startsWith('index.')).map(T),
  T('index.json'),
  path.join(ROOT, 'sections', 'header-group.json'),
  path.join(ROOT, 'sections', 'footer-group.json'),
];
for (const f of sources) {
  const raw = fs.readFileSync(f, 'utf8');
  if (!raw.includes('shopify://')) continue;
  const comment = raw.match(/^\s*\/\*[\s\S]*?\*\/\s*/)?.[0] || '';
  fs.writeFileSync(f, comment + JSON.stringify(normalise(readJSON(f)), null, 2) + '\n');
}

/* 2. Guides */
function readGuides() {
  const dir = path.join(ROOT, 'content', 'guides');
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.md'))
    .sort()
    .map((f) => {
      const raw = fs.readFileSync(path.join(dir, f), 'utf8');
      const fm = raw.match(/^---\n([\s\S]*?)\n---\n/);
      const meta = {};
      if (fm) fm[1].split('\n').forEach((l) => {
        const i = l.indexOf(':');
        if (i > 0) meta[l.slice(0, i).trim()] = l.slice(i + 1).trim();
      });
      return { ...meta, html: marked.parse(fm ? raw.slice(fm[0].length) : raw).trim() };
    });
}
const guides = readGuides();
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');
const guideList = (limit, except) =>
  `<div class="a3-grid" style="--a3-min: 28rem">${guides
    .filter((g) => g.handle !== except)
    .slice(0, limit)
    .map((g) => `<a class="a3-item" href="/blogs/guides/${g.handle}"><h3>${esc(g.title)}</h3><p class="a3-muted">${esc(g.seo_description || '')}</p></a>`)
    .join('')}</div>`;

/* 3. Page views: straight copies of the page templates */
const PAGES = ['builder', 'bundles', 'size-guide', 'team-orders', 'feedback', 'you-told-us', 'about', 'mission', 'contact', 'faq'];
const PAGE_TITLES = {
  builder: 'Kit designer', mission: 'Our mission', bundles: 'Bundles', 'size-guide': 'Size guide', 'team-orders': 'Team & club orders',
  feedback: 'Feedback', 'you-told-us': 'You told us', about: 'About', contact: 'Contact', faq: 'FAQ',
};
for (const p of PAGES) {
  writeGenerated(T(`index.${p}.json`), readJSON(T(`page.${p}.json`)));
  titles[p] = PAGE_TITLES[p];
}

/* 4. Collection views */
const soon = (eyebrow, heading, text, links) => ({
  sections: {
    main: {
      type: 'a3gk-statement',
      blocks: Object.fromEntries(links.map(([label, url], i) => [`l${i}`, { type: 'link', settings: { label, url } }])),
      block_order: links.map((_, i) => `l${i}`),
      settings: { eyebrow, heading, text, layout: 'split', tone: 'ink', padding_top: 120, padding_bottom: 120 },
    },
  },
  order: ['main'],
});
const COLLECTIONS = {
  'glove-care': ['Glove care', soon('Coming soon', 'Glove care', '<p>Our own glove wash, grip spray and deodorizer. They are in testing on match gloves now and go on sale once they pass.</p>', [['How to look after goalkeeper gloves', '/blogs/guides/how-to-clean-goalkeeper-gloves'], ['Care bundles', '/pages/bundles']])],
  'tape-socks': ['Tape & socks', soon('Coming soon', 'Tape & socks', '<p>Own-brand finger tape and grip socks. Sizes will be on the size guide before they go on sale.</p>', [['Sock sizes', '/pages/size-guide#socks'], ['What\'s worth buying as a keeper', '/blogs/guides/goalkeeper-gear-worth-buying']])],
  protection: ['Protection', soon('Coming later', 'Protection', '<p>Stock padded shorts and pants come later. You can already have padded kit made to order in the kit builder, with padding where you need it.</p>', [['Open the kit builder', '/pages/builder'], ['Goalkeeper padding, explained', '/blogs/guides/goalkeeper-padding-explained']])],
  bags: ['Bags', soon('Coming later', 'Bags', '<p>An A3GK kit bag, once a sample has survived real use. Not before.</p>', [['About A3GK', '/pages/about']])],
  bundles: ['Bundles', soon('', 'Bundles', '<p>Every bundle shows the price of each item on its own next to the bundle price.</p>', [['See the bundles', '/pages/bundles']])],
  gloves: ['Gloves', readJSON(T('collection.gloves.json'))],
};
for (const [handle, [title, tpl]] of Object.entries(COLLECTIONS)) {
  writeGenerated(T(`index.c-${handle}.json`), tpl);
  titles[`c-${handle}`] = title;
}

/* 5. Guide views */
writeGenerated(T('index.guides.json'), {
  sections: {
    main: {
      type: 'a3gk-prose',
      settings: { heading: 'Guides', intro: 'Glove care, choosing gloves, padding and sizing, from a keeper-only store.', html: guideList(99), narrow: false, tone: 'ink', padding_top: 96, padding_bottom: 112 },
    },
  },
  order: ['main'],
});
titles.guides = 'Guides';
for (const g of guides) {
  writeGenerated(T(`index.guide-${g.handle}.json`), {
    sections: {
      main: {
        type: 'a3gk-prose',
        settings: { heading: g.title, intro: '', html: g.html, narrow: true, tone: 'ink', padding_top: 96, padding_bottom: 96 },
      },
      more: {
        type: 'a3gk-prose',
        settings: { heading: '', intro: '', html: `<h2>More guides</h2>${guideList(99, g.handle)}`, narrow: false, tone: 'raised', padding_top: 80, padding_bottom: 96 },
      },
    },
    order: ['main', 'more'],
  });
  titles[`guide-${g.handle}`] = g.title;
}

/* 6. Homepage guides: built in, so it never shows empty blog placeholders */
const home = readJSON(T('index.json'));
if (home.sections.guides) {
  home.sections.guides = {
    type: 'a3gk-prose',
    settings: {
      heading: '',
      intro: '',
      html: `<div class="a3-head" style="margin-bottom:3.2rem"><h2>Guides</h2><p><a class="a3-link" href="/blogs/guides">All guides</a></p></div>${guideList(3)}`,
      narrow: false,
      tone: 'ink',
      padding_top: 96,
      padding_bottom: 112,
    },
  };
  writeJSON(T('index.json'), home);
}

/* 7. Titles for <title> */
const cases = Object.entries(titles)
  .map(([view, title]) => `  {%- when '${view}' -%}${title.replace(/&/g, '&amp;')}`)
  .join('\n');
fs.writeFileSync(
  path.join(ROOT, 'snippets', 'a3gk-view-title.liquid'),
  `{%- comment -%}\n  Generated by tools/gen-fallback-templates.mjs — page titles for the built-in views.\n  Accepts: view (template suffix)\n{%- endcomment -%}\n{%- case view -%}\n${cases}\n{%- endcase -%}\n`
);

console.log(`Generated ${Object.keys(titles).length} built-in views.`);
